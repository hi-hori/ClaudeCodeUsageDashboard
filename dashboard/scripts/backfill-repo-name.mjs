#!/usr/bin/env node
//
// Rename stored repositories after the naming rule in app/lib/repo-name.ts
// changes (e.g. "trunk" became "TMSR7/trunk").
//
// repo_name is computed at ingest and stored, in sessions and in the
// tool_usage_daily rollup, so a new rule only applies to new uploads. Without
// this backfill the history stays under the old name and every session that
// continues afterwards splits across two repositories.
//
// The script reads the distinct (project_dir, repo_name) pairs with wrangler,
// names them with the same function ingest uses, and writes SQL that
//
//   1. updates sessions.repo_name per project_dir, then
//   2. rebuilds tool_usage_daily for every affected name (old and new) from
//      session_tool_counts, which holds per session exactly what ingest
//      credited to the rollup.
//
// Step 2 deletes and re-inserts the whole set of affected names, so the file
// is idempotent: if applying it fails halfway, apply the same file again (do
// not regenerate it — after step 1 the old names are gone from sessions and a
// new run would find nothing to do).
//
// Usage (Node 22.18+ / 23.6+, which load the .ts file directly):
//
//   cd dashboard
//   node scripts/backfill-repo-name.mjs --remote            # or --local
//   (review backfill-repo-name.sql)
//   npx wrangler d1 execute claude-code-usage-dashboard-v2 --remote --file ./backfill-repo-name.sql
//
// Options: --db <name> (default: claude-code-usage-dashboard-v2),
//          --out <file> (default: ./backfill-repo-name.sql).

import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { repoNameFromProjectDir } from "../app/lib/repo-name.ts";

const args = process.argv.slice(2);
const opt = (name, fallback) => {
  const i = args.indexOf(name);
  return i >= 0 && i + 1 < args.length ? args[i + 1] : fallback;
};
const target = args.includes("--remote") ? "--remote" : args.includes("--local") ? "--local" : null;
if (!target) {
  console.error("Specify --remote or --local.");
  process.exit(2);
}
const db = opt("--db", "claude-code-usage-dashboard-v2");
const out = opt("--out", "./backfill-repo-name.sql");

const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const list = (values) => values.map(q).join(", ");

function query(sql) {
  // SQL here never contains double quotes, so it can be quoted for the shell as-is.
  const stdout = execSync(`npx wrangler d1 execute ${db} ${target} --json --command "${sql}"`, {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "inherit"],
    maxBuffer: 256 * 1024 * 1024,
  });
  const json = JSON.parse(stdout.slice(stdout.indexOf("[")));
  return json[0].results;
}

const pairs = query("SELECT DISTINCT project_dir, repo_name FROM sessions");
const changes = pairs
  .map((r) => ({ dir: r.project_dir, from: r.repo_name, to: repoNameFromProjectDir(r.project_dir) }))
  .filter((c) => c.from !== c.to);

if (changes.length === 0) {
  console.log("Every stored repo_name already follows the current rule. Nothing to do.");
  process.exit(0);
}

const names = [...new Set(changes.flatMap((c) => [c.from, c.to]))].sort();

// The rebuild trusts session_tool_counts to add up to what tool_usage_daily
// holds for these names. Check before writing anything that throws the
// rollup away.
const [rollup] = query(
  `SELECT COALESCE(SUM(call_count), 0) AS n FROM tool_usage_daily WHERE repo_name IN (${list(names)})`
);
const [perSession] = query(
  `SELECT COALESCE(SUM(stc.call_count), 0) AS n FROM session_tool_counts stc ` +
    `JOIN (SELECT DISTINCT session_id FROM sessions WHERE repo_name IN (${list(names)})) s ` +
    `ON s.session_id = stc.session_id`
);
if (rollup.n !== perSession.n) {
  console.error(
    `tool_usage_daily holds ${rollup.n} calls for the affected names, but session_tool_counts ` +
      `adds up to ${perSession.n}. Rebuilding would change the totals; investigate before renaming.`
  );
  process.exit(1);
}

const sql = [
  "-- Generated by scripts/backfill-repo-name.mjs. Idempotent: re-apply this same file if it fails halfway.",
  "",
  ...changes.map((c) => `-- ${c.from} -> ${c.to}\nUPDATE sessions SET repo_name = ${q(c.to)} WHERE project_dir = ${q(c.dir)};`),
  "",
  `DELETE FROM tool_usage_daily WHERE repo_name IN (${list(names)});`,
  "",
  `INSERT INTO tool_usage_daily (day, user_id, repo_name, kind, name, call_count)
SELECT stc.day, s.user_id, s.repo_name, stc.kind, stc.name, SUM(stc.call_count)
FROM session_tool_counts stc
JOIN (SELECT DISTINCT session_id, user_id, repo_name FROM sessions WHERE repo_name IN (${list(names)})) s
  ON s.session_id = stc.session_id
WHERE true
GROUP BY stc.day, s.user_id, s.repo_name, stc.kind, stc.name
ON CONFLICT(day, user_id, repo_name, kind, name) DO UPDATE SET
  call_count = tool_usage_daily.call_count + excluded.call_count;`,
  "",
].join("\n");

writeFileSync(out, sql);
console.log(`${changes.length} project_dir(s) renamed (${rollup.n} tool calls rebuilt). Wrote ${out}:`);
for (const c of changes) console.log(`  ${c.from} -> ${c.to}    (${c.dir})`);
